'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const players=require('./player-data.json');
const ability=require('./player-ability'),fit=require('./draft-fit');
const {normalize,imported}=require('./cricinfo-import');
const byId=new Map(players.map(p=>[p.id,p]));const p=id=>byId.get(id);
assert.equal(ability.VERSION,'all-time-legends-v23-cricinfo-import');
assert.equal(players.length,793);
const source=JSON.parse(fs.readFileSync('./cricinfo-id-map.json','utf8'));
for(const [id,espn] of Object.entries(source))assert.equal(p(id).cricinfo.id,espn);
const row={gameId:'virat-kohli',espnId:253802,format:'T20I',m:125,runs:4188,avg:48.7,sr:137.04,wk:0,ba:null,eco:null,asOf:'2026-11-17'};
const enriched=imported(players,[row]);const changed=enriched.find(x=>x.id==='virat-kohli');
assert.equal(changed.cricinfo.formats.T20I.avg,48.7);
const probed=ability.profile(changed);
assert.equal(probed.record.provider,'ESPNcricinfo Statsguru');
assert.equal(probed.record.format,'T20I');
assert.equal(probed.record.average,48.7);
assert.equal(probed.record.strikeRate,137.04);
assert.equal(probed.record.asOf,'2026-11-17');
assert.match(probed.record.source,/engine\/player\/253802\.html/);
assert.equal(probed.record.verified,true);
assert.ok(probed.bat.overall>ability.profile(p('india-roger-binny')).bat.overall+20);
assert.throws(()=>normalize([{...row,espnId:111111}],players),/ID mismatch/);
assert.throws(()=>normalize([{...row,avg:9999}],players),/Invalid numeric/);
const stat={id:'fictional',fmt:'T20I',avg:39,sr:148,ba:22,eco:7.2,wk:65,m:80};
const ar=ability.profile({...stat,role:'A'}),bat=ability.profile({...stat,role:'B'});
assert.equal(ar.bat.overall,bat.bat.overall);
assert.equal(ar.bowl.overall,bat.bowl.overall);
const team=['shakib-al-hasan','shane-watson','glenn-maxwell','andre-russell','jasprit-bumrah','malcolm-marshall'].map(p);
assert.equal(fit.rate(p('gulbadin-naib'),team,ability).bowlingGain,0);
assert.ok(fit.rate(p('bangladesh-jaker-ali'),[],ability).score<fit.rate(p('shakib-al-hasan'),[],ability).score,'Unknown keeper must not jump ahead of known internationals in early drafts');
assert.ok(fit.rate(p('india-sanju-samson'),[],ability).score<fit.rate(p('virat-kohli'),[],ability).score,'Early drafts should not auto-prefer unverified wicketkeepers');
assert.ok(fit.rate(p('bangladesh-jaker-ali'),new Array(10).fill(p('virat-kohli')),ability).score>fit.rate(p('bangladesh-jaker-ali'),[],ability).score,'Late XI keeper need is real, unlike early keeper bias');
assert.ok(fit.rate(p('babar-azam'),team,ability).score>fit.rate(p('gulbadin-naib'),team,ability).score+6);
assert.ok(fit.rate(p('jasprit-bumrah'),[],ability).bowlingGain>0);
const html=fs.readFileSync('./index.html','utf8');
assert.ok(html.includes(fs.readFileSync('./player-ability.js','utf8').trim()));
assert.ok(html.includes(fs.readFileSync('./draft-fit.js','utf8').trim()));
assert.ok(html.includes('ESPN STATS'));
console.log('PASS V23: validated Statsguru import, safe ESPN IDs, role parity, no sixth-bowler bonus, browser/server parity');
